<#
.SYNOPSIS
    Fetches the Phosphor icon font and writes the glyph map the card binds to.

.DESCRIPTION
    Run once, by hand. The card's icons were hand-authored Path geometry across five stroke weights
    and seven Viewbox sizes, which is why they read as drawn; this replaces them with a real set.

    Two files come down: the TTF, which ships in the app, and the stylesheet, which is the only
    place the name-to-codepoint mapping exists. The script resolves the names the card actually
    uses and writes them into a XAML resource dictionary, so a missing or renamed icon fails here,
    at generation time, rather than rendering as tofu on a phone.

    Swapping to Nucleo (or any other icon font) means changing $Ttf/$Css and the $Wanted names.
    Nothing downstream of this script cares which set it was.

.EXAMPLE
    pwsh -File ./scripts/Fetch-Icons.ps1 -Verbose
#>
[CmdletBinding()]
param(
    # Phosphor ships one file per weight. Regular is the body-text weight; Bold pairs with SemiBold.
    [string]$Ttf = 'https://cdn.jsdelivr.net/npm/@phosphor-icons/web@2/src/regular/Phosphor.ttf',
    [string]$Css = 'https://cdn.jsdelivr.net/npm/@phosphor-icons/web@2/src/regular/style.css',

    [string]$TtfOut = "$PSScriptRoot/../MorningCard/Assets/Fonts/Phosphor_Regular.ttf",
    [string]$MapOut = "$PSScriptRoot/../MorningCard/Themes/Icons.xaml"
)

$ErrorActionPreference = 'Stop'

# The card's icons, by the role they play rather than by their glyph name, so a rename upstream is
# a one-line edit here instead of a hunt through the XAML.
$Wanted = [ordered]@{
    Greeting    = 'sun'
    ChevronNext = 'caret-right'
    Disclosure  = 'caret-down'
    Checklist   = 'list-checks'
    Fuel        = 'gas-pump'
    Cabin       = 'thermometer-simple'
    Parking     = 'car-simple'
    Lock        = 'lock-simple'
    Unlock      = 'lock-simple-open'
    Drive       = 'navigation-arrow'
    Overflow    = 'dots-three'
    MapPin      = 'map-pin'
}

Write-Verbose "GET $Css"
$style = Invoke-RestMethod -Uri $Css -TimeoutSec 60

# Phosphor's stylesheet carries one rule per icon: `.ph.ph-gas-pump:before { content: "\e2a4"; }`
$codepoints = @{}
foreach ($m in [regex]::Matches($style, '\.ph\.ph-([a-z0-9-]+):before\s*\{\s*content:\s*"\\([0-9a-fA-F]+)"')) {
    $codepoints[$m.Groups[1].Value] = $m.Groups[2].Value.ToUpperInvariant()
}
"stylesheet: {0:N0} icons" -f $codepoints.Count | Write-Host

$missing = $Wanted.Values | Where-Object { -not $codepoints.ContainsKey($_) }

if ($missing) {
    throw "Not in this icon set: $($missing -join ', '). Pick alternates before rerunning - a glyph that does not exist renders as tofu, silently, and only on the head you did not check."
}

Write-Verbose "GET $Ttf"
$resolvedTtf = [System.IO.Path]::GetFullPath($TtfOut)
New-Item -ItemType Directory -Force -Path (Split-Path $resolvedTtf) | Out-Null
Invoke-WebRequest -Uri $Ttf -OutFile $resolvedTtf -TimeoutSec 120

# Magic bytes: a real TrueType file starts 00 01 00 00. A CDN error page does not, and would
# otherwise install cleanly and fall back to the default face at runtime.
$head = [System.IO.File]::ReadAllBytes($resolvedTtf)[0..3]

if (-not ($head[0] -eq 0 -and $head[1] -eq 1 -and $head[2] -eq 0 -and $head[3] -eq 0)) {
    throw "$resolvedTtf is not a TrueType file (starts $([BitConverter]::ToString($head))). The URL probably served an error page."
}

"wrote {0} ({1:N0} bytes)" -f $resolvedTtf, (Get-Item $resolvedTtf).Length | Write-Host

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"')
$lines.Add('                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">')
$lines.Add('')
$lines.Add('  <!--')
$lines.Add('    GENERATED by scripts/Fetch-Icons.ps1. Do not hand-edit: rerun the script.')
$lines.Add('')
$lines.Add('    One icon set, one weight, one FontFamily. The card drew its own Path geometry before')
$lines.Add('    this, across five stroke weights and seven Viewbox sizes, which is what made the icons')
$lines.Add('    read as drawn rather than as a set.')
$lines.Add('  -->')
$lines.Add('')
$lines.Add('  <FontFamily x:Key="IconFont">ms-appx:///Assets/Fonts/Phosphor_Regular.ttf#Phosphor</FontFamily>')
$lines.Add('')

foreach ($role in $Wanted.Keys) {
    $name = $Wanted[$role]
    $code = $codepoints[$name]
    $lines.Add("  <!-- $name -->")
    $lines.Add("  <x:String x:Key=""Icon$role"">&#x$code;</x:String>")
}

$lines.Add('')
$lines.Add('</ResourceDictionary>')

$resolvedMap = [System.IO.Path]::GetFullPath($MapOut)
$lines -join "`n" | Set-Content -Path $resolvedMap -Encoding utf8NoBOM
"wrote $resolvedMap ($($Wanted.Count) glyphs)" | Write-Host
